DECLARE @Api NChar(1) -- StringFixedLength
SET     @Api = N'F'

SELECT
	[p].[FirstName],
	[p].[PersonID],
	[p].[LastName],
	[p].[MiddleName],
	[p].[Gender]
FROM
	[Person] [p]
WHERE
	CASE
		WHEN [p].[PersonID] > 2 THEN N'M'
		ELSE N'F'
	END IN (@Api)

