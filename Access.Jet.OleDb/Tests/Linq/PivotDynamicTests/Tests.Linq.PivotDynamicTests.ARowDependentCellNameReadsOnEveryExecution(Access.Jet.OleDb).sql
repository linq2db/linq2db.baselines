SELECT
	SUM(IIF([r].[Year] = 2000, [r].[Amount], NULL)),
	SUM(IIF([r].[Year] = 2010, [r].[Amount], NULL)),
	IIF([r].[Category] = 'A', 'Y2000', 'Y2010')
FROM
	[CategorySales] [r]
GROUP BY
	[r].[Category]
ORDER BY
	[r].[Category]

