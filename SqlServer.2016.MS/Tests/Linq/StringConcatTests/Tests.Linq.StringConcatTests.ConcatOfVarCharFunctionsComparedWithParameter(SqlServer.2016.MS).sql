SELECT
	COUNT(*)
FROM
	[SplitVarCharRow] [t]
WHERE
	(CAST(Upper([t].[Left]) + Upper([t].[Right]) AS NVarChar(Max)) + Coalesce(@suffix, N'')) = @expected

