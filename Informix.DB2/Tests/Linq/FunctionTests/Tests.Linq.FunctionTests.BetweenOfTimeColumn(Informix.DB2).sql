SELECT
	r.Id
FROM
	BetweenTimeRow r
WHERE
	r."Value" BETWEEN INTERVAL(0 01:30:00.00000) DAY TO FRACTION(5) AND INTERVAL(0 03:00:00.00000) DAY TO FRACTION(5)
ORDER BY
	r.Id

