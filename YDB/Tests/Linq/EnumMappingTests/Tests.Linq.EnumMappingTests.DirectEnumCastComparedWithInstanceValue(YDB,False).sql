DECLARE Api Text(1) -- AnsiStringFixedLength
SET     Api = 'F'u

SELECT
	p.FirstName as FirstName,
	p.PersonID as PersonID,
	p.LastName as LastName,
	p.MiddleName as MiddleName,
	p.Gender as Gender
FROM
	Person p
WHERE
	p.Gender = $Api

