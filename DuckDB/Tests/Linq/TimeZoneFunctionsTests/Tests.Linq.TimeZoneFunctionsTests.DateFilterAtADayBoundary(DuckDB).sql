-- DuckDB
DECLARE $date TIMESTAMP -- DateTime2
SET     $date = '2020-12-31 00:00:00.000000'::TIMESTAMP

SELECT
	COUNT(*)
FROM
	ZonedRow r
WHERE
	CAST(CAST((r.Dto AT TIME ZONE 'UTC') AS DATE) AS TIMESTAMP) = $date

