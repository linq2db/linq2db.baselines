-- SqlServer.2025
DECLARE @Gender Char(1) -- AnsiStringFixedLength
SET     @Gender = N'F'

SELECT
	[p].[FirstName],
	[p].[PersonID],
	[p].[LastName],
	[p].[MiddleName],
	[p].[Gender]
FROM
	[Person] [p]
WHERE
	@Gender = [p].[Gender]

