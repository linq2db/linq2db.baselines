-- SqlServer.2012
DECLARE @missing Char(2) -- AnsiStringFixedLength
SET     @missing = N'99'

SELECT
	[p].[FirstName],
	[p].[PersonID],
	[p].[LastName],
	[p].[MiddleName],
	[p].[Gender]
FROM
	[Person] [p]
WHERE
	[p].[Gender] = @missing

