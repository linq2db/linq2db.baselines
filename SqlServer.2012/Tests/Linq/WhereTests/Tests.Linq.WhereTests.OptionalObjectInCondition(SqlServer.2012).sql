-- SqlServer.2012
DECLARE @Id NVarChar(4000) -- String
SET     @Id = N'1'

SELECT
	[r].[FirstName],
	[r].[PersonID],
	[r].[LastName],
	[r].[MiddleName],
	[r].[Gender]
FROM
	[Person] [r]
WHERE
	[r].[FirstName] = @Id

