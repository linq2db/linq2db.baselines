DECLARE @missing Char(2) -- String
SET     @missing = '99'

SELECT
	p."FirstName",
	p."PersonID",
	p."LastName",
	p."MiddleName",
	p."Gender"
FROM
	"Person" p
WHERE
	p."Gender" <> :missing

