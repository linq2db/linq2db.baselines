-- PostgreSQL.9.2 PostgreSQL
DECLARE @gender Char(1) -- String
SET     @gender = 'F'

SELECT
	p."FirstName",
	p."PersonID",
	p."LastName",
	p."MiddleName",
	p."Gender"
FROM
	"Person" p
WHERE
	p."Gender"::text = :gender

