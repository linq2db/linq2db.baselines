-- Sybase.Managed Sybase
DECLARE @Api UniChar(1) -- StringFixedLength
SET     @Api = 'F'

SELECT
	[p].[FirstName],
	[p].[PersonID],
	[p].[LastName],
	[p].[MiddleName],
	[p].[Gender]
FROM
	[Person] [p]
WHERE
	CASE
		WHEN [p].[PersonID] > 2 THEN 'M'
		ELSE 'F'
	END IN (@Api)

