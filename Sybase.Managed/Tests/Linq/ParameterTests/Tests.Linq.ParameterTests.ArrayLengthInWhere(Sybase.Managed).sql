-- Sybase.Managed Sybase
DECLARE @arr Integer -- Int32
SET     @arr = 1

SELECT
	[p].[FirstName],
	[p].[PersonID],
	[p].[LastName],
	[p].[MiddleName],
	[p].[Gender]
FROM
	[Person] [p]
WHERE
	[p].[PersonID] = @arr

